#!/usr/bin/env python3
"""Regenerates modules/nexus/SearchIndex.qml, the data behind Nexus' "Search settings" bar.

Walks PageCompRegistry.qml to learn which page file lives at which
(page index, sub-page index), then pulls every `text:`/`label:` string (plus
the `subtext:` that follows it) out of those files.

Run after adding or renaming settings:  python3 scripts/gen-nexus-search-index.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "modules" / "nexus"

# Pages that need runtime state (a selected device/network/...) to open, so
# they can't be a search target.
SKIP = {
    "NetworkDetailPage", "EthernetDetailPage", "BtDeviceInfo", "OutputDetailPage",
    "WallpaperCategory", "AppInfo", "AddNetworkPage", "AddVpnPage", "BluetoothPairing",
    "PluginDetailPage", "PluginSettingsPage",
}

# Sub-pages that are only reachable through another sub-page: (page, sub) -> parent sub.
# Taskbar component pages (6-11 of Panels) open from the Taskbar page (2).
PARENT_SUB = {(8, n): 2 for n in range(6, 12)}

STR = r'qsTr\("((?:[^"\\]|\\.)*)"\)'
LABEL_RE = re.compile(r"^\s*(?:text|label):\s*" + STR + r"\s*$")
SUBTEXT_RE = re.compile(r"^\s*subtext:\s*(.*)$")
TITLE_RE = re.compile(r"^\s*title:\s*" + STR)


def find_file(name: str) -> Path | None:
    hits = list((ROOT / "pages").rglob(f"{name}.qml"))
    return hits[0] if hits else None


def parse_registry():
    """-> list of pages, each a list of component names (index = sub-page idx)."""
    text = (ROOT / "PageCompRegistry.qml").read_text()
    body = text[text.index("readonly property list<Component> pageComps"):text.index("readonly property Component placeholderComp")]
    pages = []
    for block in re.split(r"\n        (?=Component \{|// )", body):
        if "StackPage" in block:
            pages.append(re.findall(r"Component \{\s*(\w+) \{\}", block.split("StackPage", 1)[1]))
        elif "PlaceholderComp" in block and "Component {" in block:
            pages.append([])
    return pages


def page_labels():
    text = (ROOT / "PageRegistry.qml").read_text()
    return re.findall(r"label: qsTr\(\"((?:[^\"\\]|\\.)*)\"\)", text)


def is_searchable(label: str) -> bool:
    """Drops sentences, placeholders and empty-state messages; keeps setting names."""
    return (
        len(label) <= 40
        and not label.endswith(".")
        and not label.startswith(("No ", "Page under"))
        and "%" not in label
    )


def js(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tr(s: str) -> str:
    return f"qsTr({js(s)})" if s and "%" not in s else '""'


def main():
    pages = parse_registry()
    labels = page_labels()
    assert len(pages) == len(labels), (len(pages), len(labels))

    entries = []
    for page_idx, comps in enumerate(pages):
        for sub_idx, comp in enumerate(comps):
            if comp in SKIP:
                continue
            f = find_file(comp)
            if not f:
                continue
            lines = f.read_text().splitlines()
            title = next((m.group(1) for l in lines if (m := TITLE_RE.match(l))), None)
            stack = []
            if sub_idx:
                if (page_idx, sub_idx) in PARENT_SUB:
                    stack.append(PARENT_SUB[(page_idx, sub_idx)])
                stack.append(sub_idx)
            path = labels[page_idx] + (f" › {title}" if title and sub_idx and title != labels[page_idx] else "")

            seen = set()
            last = None
            for l in lines:
                m = LABEL_RE.match(l)
                if m:
                    label = m.group(1)
                    if label in seen or label == title or not is_searchable(label):
                        last = None
                        continue
                    seen.add(label)
                    last = {"label": label, "sub": "", "page": page_idx, "stack": stack, "path": path}
                    entries.append(last)
                    continue
                m = SUBTEXT_RE.match(l)
                if m and last is not None:
                    strs = re.findall(STR, m.group(1))
                    # Skip dynamic status subtexts (state-dependent ternaries).
                    if len(strs) == 1 and m.group(1).strip().startswith("qsTr("):
                        last["sub"] = strs[0]
                    last = None

    out = ["// Generated by scripts/gen-nexus-search-index.py - do not edit by hand.",
           "pragma Singleton", "", "import QtQuick", "", "QtObject {",
           "    readonly property list<var> entries: ["]
    for e in entries:
        out.append(
            f"        {{label: qsTr({js(e['label'])}), sub: {tr(e['sub'])}, path: {js(e["path"])}, "
            f"page: {e['page']}, stack: [{', '.join(map(str, e['stack']))}]}},"
        )
    out += ["    ]", "}", ""]
    (ROOT / "SearchIndex.qml").write_text("\n".join(out))
    print(f"wrote {len(entries)} entries")


main()
